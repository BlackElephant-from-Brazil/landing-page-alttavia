#!/usr/bin/env -S npx tsx
/**
 * Writes supabase/migrations/0003_seed_questions.sql from SEED_QUESTIONS in
 * src/lib/apply/questions.ts, so the database seed and the code's fallback
 * cannot drift.
 *
 *   npx tsx scripts/generate-questions-seed.mjs
 *
 * Runs under tsx (already a devDependency) because the seed lives in a
 * TypeScript module that imports the wizard copy through the `@/` alias;
 * tsx resolves both from tsconfig.json. Plain `node` cannot run it.
 *
 * Every row is `insert ... on conflict (key) do update`, so rerunning the
 * migration after a copy change refreshes the rows in place and keeps the
 * ids that user_answers already point at. `npm run db:migrate` applies each
 * file once; to reapply an edited seed, delete its row from
 * public.schema_migrations first or post the file by hand.
 */

import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { SEED_QUESTIONS } from "../src/lib/apply/questions.ts";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "supabase", "migrations", "0003_seed_questions.sql");

/** A SQL string literal, or NULL. */
function text(value) {
  if (value === null || value === undefined) return "null";
  return `'${String(value).replace(/'/g, "''")}'`;
}

/** A jsonb literal, or NULL. Pretty printed so the file reads as a document. */
function json(value) {
  if (value === null || value === undefined) return "null";
  const body = JSON.stringify(value, null, 2)
    .replace(/'/g, "''")
    .split("\n")
    .map((line, i) => (i === 0 ? line : `    ${line}`))
    .join("\n");
  return `'${body}'::jsonb`;
}

function rowSql(q) {
  return [
    "  (",
    `    ${text(q.id)},`,
    `    ${text(q.key)},`,
    `    ${text(q.answer_key)},`,
    `    ${q.position},`,
    `    ${text(q.kind)},`,
    `    ${text(q.title)},`,
    `    ${text(q.help)},`,
    `    ${json(q.options)},`,
    `    ${json(q.extras)},`,
    `    ${json(q.visible_when)},`,
    `    ${q.active ? "true" : "false"}`,
    "  )",
  ].join("\n");
}

const header = `-- 0003_seed_questions.sql
--
-- GENERATED by scripts/generate-questions-seed.mjs from SEED_QUESTIONS in
-- src/lib/apply/questions.ts. Do not edit by hand: change the seed (or the
-- copy it imports from src/content/apply.ts) and run
--
--   npx tsx scripts/generate-questions-seed.mjs
--
-- The six questions of the initial form, in the order the wizard asks them.
-- \`visible_when\` is the rule grammar of docs/platform-contract.md section 6,
-- \`extras\` carries the copy the wizard needs beyond title and options (see
-- WizardExtras in questions.ts). Rows are matched by \`key\`, so rerunning
-- the file updates copy in place and leaves ids untouched.
--
-- The seven house rules in the src/content/bank-nif.ts header apply to
-- every string here.

insert into public.questions (
  id, key, answer_key, position, kind, title, help, options, extras, visible_when, active
) values
`;

const footer = `
on conflict (key) do update set
  answer_key   = excluded.answer_key,
  position     = excluded.position,
  kind         = excluded.kind,
  title        = excluded.title,
  help         = excluded.help,
  options      = excluded.options,
  extras       = excluded.extras,
  visible_when = excluded.visible_when,
  active       = excluded.active;
`;

const rows = [...SEED_QUESTIONS].sort((x, y) => x.position - y.position);
const sql = header + rows.map(rowSql).join(",\n") + footer;

writeFileSync(OUT, sql, "utf8");
console.log(`Wrote ${rows.length} question rows to ${OUT}`);
